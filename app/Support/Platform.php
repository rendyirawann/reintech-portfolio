    /** Nama platform dari URL, atau 'link' bila tidak dikenali. */
    public static function dariUrl(?string $url): string
    {
        if (blank($url)) {
            return 'link';
        }

        // Diperiksa DULUAN: `mailto:` tidak memakai `//`, sehingga penambahan
        // skema di bawah akan merusaknya menjadi "https://mailto:...".
        if (str_starts_with(strtolower($url), 'mailto:')) {
            return 'email';
        }

        // Tanpa skema, parse_url() menaruh seluruhnya di `path` dan host jadi
        // kosong — jadi skema ditambahkan dulu bila pengguna mengetik
        // "github.com/rendy" saja.
        if (!preg_match('~^[a-z][a-z0-9+.\-]*://~i', $url)) {
            $url = 'https://' . ltrim($url, '/');
        }

        $host = strtolower((string) parse_url($url, PHP_URL_HOST));
        if ($host === '') {
            return 'link';
        }

        $host = preg_replace('/^www\./', '', $host);

        if (isset(self::PETA[$host])) {
            return self::PETA[$host];
        }

        // Subdomain: "gist.github.com" tetap GitHub, "id.linkedin.com" tetap
        // LinkedIn. Dicocokkan dari kanan agar "github.com.penipu.id" TIDAK
        // ikut terbaca sebagai GitHub.
        foreach (self::PETA as $domain => $nama) {
            if (str_ends_with($host, '.' . $domain)) {
                return $nama;
            }
        }

        return 'link';
    }

